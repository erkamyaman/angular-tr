/**
 * firebase.json and .firebaserc for every configured language.
 *
 * Hosting rules (headers for WebContainers, caching, rewrites) are copied from upstream's
 * adev/firebase.json at the pinned commit, so they never drift; only `target` and `public`
 * are ours. One hosting target per language; several projects are supported.
 */
import path from 'node:path';
import {exists, readJson, readText, writeText} from './fs.mjs';
import {listLanguages, loadSite} from './languages.mjs';
import {originDir, rootDir} from './paths.mjs';

const PUBLIC_DIR = (lang) => `build/${lang}/dist/bin/adev/dist/browser`;

/** Compute the two files. Returns {'firebase.json': text, '.firebaserc': text}. Throws when something is missing. */
export async function renderFirebaseConfig({includeExample = false} = {}) {
  const upstreamConfigPath = path.join(originDir, 'adev', 'firebase.json');
  if (!(await exists(upstreamConfigPath))) {
    throw new Error(`upstream firebase.json not found at ${upstreamConfigPath}. Run: pnpm bootstrap`);
  }
  const upstream = await readJson(upstreamConfigPath);
  const base = Array.isArray(upstream.hosting) ? upstream.hosting[0] : upstream.hosting;
  if (!base) throw new Error('upstream firebase.json has no hosting section');

  const languages = await listLanguages({includeExample});
  if (!languages.length) throw new Error('no language configured; run pnpm create-language <lang>');

  const hosting = [];
  const projects = {};
  const targets = {};
  for (const lang of languages) {
    const site = await loadSite(lang);
    const {target, projectId, site: siteId} = site.firebase;
    hosting.push({...base, target, public: PUBLIC_DIR(lang)});
    projects.default ??= projectId;
    (targets[projectId] ??= {hosting: {}}).hosting[target] = [siteId ?? projectId];
    if (site.firebase.stagingProjectId) {
      const stagingTarget = site.firebase.stagingTarget ?? `${target}-staging`;
      hosting.push({...base, target: stagingTarget, public: PUBLIC_DIR(lang)});
      (targets[site.firebase.stagingProjectId] ??= {hosting: {}}).hosting[stagingTarget] = [site.firebase.stagingProjectId];
      projects.staging ??= site.firebase.stagingProjectId;
    }
  }

  const firebaseJson = {
    '//': 'Generated by `pnpm firebase-config` from i18n/*/site.json and origin/adev/firebase.json. Do not edit by hand.',
    hosting,
  };
  return {
    'firebase.json': JSON.stringify(firebaseJson, null, 2) + '\n',
    '.firebaserc': JSON.stringify({projects, targets}, null, 2) + '\n',
  };
}

/**
 * Write (or, with check, only compare) the files at the repository root.
 * Returns {stale: [names that differed], written: [names written]}.
 */
export async function syncFirebaseConfig({includeExample = false, check = false} = {}) {
  const files = await renderFirebaseConfig({includeExample});
  const stale = [];
  const written = [];
  for (const [name, content] of Object.entries(files)) {
    const file = path.join(rootDir, name);
    const current = (await exists(file)) ? await readText(file) : null;
    if (current === content) continue;
    stale.push(name);
    if (!check) {
      await writeText(file, content);
      written.push(name);
    }
  }
  return {stale, written};
}
