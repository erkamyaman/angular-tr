/**
 * Site search (Algolia) and analytics wiring.
 *
 * adev reads its Algolia credentials and Google Analytics id from adev/src/app/environment.ts,
 * a plain TypeScript object. The build rewrites that file from site.json (see
 * environmentSource); the search UI itself (dialog, results, "Search by Algolia") is upstream's,
 * untouched. The index is filled by the Algolia Crawler with the configuration crawlerConfig
 * generates, which produces DocSearch records in the shape adev's search service expects:
 * hierarchy.lvl0 ("Docs" | "Tutorials" | "Reference", which the service uses to pick icons and
 * package badges), lvl1..lvl6, content, url. See docs/search.md.
 */
import {Buffer} from 'node:buffer';

const CRAWLER_API = 'https://crawler.algolia.com/api/1';

/** A string in single quotes for TypeScript / JavaScript source. */
function quote(s) {
  return `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

/**
 * Rewrite upstream's environment.ts for a site: Algolia credentials when the site has its own
 * index (provider docsearch or algolia), the site's GA4 id or an empty string otherwise. Every
 * replacement must match exactly once; when upstream changes the file's shape the build stops
 * here instead of shipping Google's analytics id or a half-patched file.
 */
export function environmentSource(upstreamText, site) {
  let text = upstreamText;
  const replaceOnce = (re, replacement, what) => {
    const matches = text.match(re);
    if (!matches || matches.length !== 1) {
      throw new Error(`environment.ts: expected exactly one ${what} (found ${matches?.length ?? 0}); upstream changed adev/src/app/environment.ts, update tools/lib/search.mjs`);
    }
    text = text.replace(re, replacement);
  };
  const search = site.search ?? {provider: 'none'};
  if (search.provider && search.provider !== 'none') {
    replaceOnce(/\bappId:\s*'[^']*'/g, `appId: ${quote(search.appId)}`, 'appId');
    replaceOnce(/\bapiKey:\s*'[^']*'/g, `apiKey: ${quote(search.apiKey)}`, 'apiKey');
    // `const indexName = isPreRelease ? … : \`angular_v${major}\`;` keeps its name so the object
    // literal below it still compiles unchanged.
    replaceOnce(/\bconst indexName\s*=[^;]*;/g, `const indexName = ${quote(search.indexName)}; // rosetta: ${site.folder ?? site.lang}`, 'indexName constant');
  }
  const analytics = site.analytics ?? {provider: 'none'};
  const gaId = analytics.provider === 'ga4' ? analytics.id : '';
  replaceOnce(/\bgoogleAnalyticsId:\s*'[^']*'/g, `googleAnalyticsId: ${quote(gaId)}`, 'googleAnalyticsId');
  return text;
}

/** Paths crawled per section; lvl0 is what adev's search service switches on. */
export const CRAWL_SECTIONS = [
  {lvl0: 'Tutorials', paths: ['/tutorials/**'], pageRank: 0},
  {lvl0: 'Reference', paths: ['/reference/**', '/errors/**', '/extended-diagnostics/**'], pageRank: -1000},
  {lvl0: 'Docs', paths: ['/**'], pageRank: 0},
];

/**
 * Paths never crawled: the API and CLI reference stay in English (search them on angular.dev),
 * and are large enough to blow the 10,000-record cap of the DocSearch program; the playground
 * and the update guide are tools, not prose.
 */
export const CRAWL_EXCLUSIONS = ['/api/**', '/cli/**', '/playground**', '/update-guide**', '/assets/**', '/404**'];

/**
 * Algolia Crawler configuration for a site, as JavaScript source to paste into the Crawler
 * editor (DocSearch program or your own application). `siteUrl` without trailing slash.
 */
export function crawlerConfig(site, {appId = site.search?.appId ?? 'YOUR_APP_ID', indexName = site.search?.indexName ?? `angular_${site.lang.toLowerCase().replace(/-/g, '_')}`, apiKey = 'YOUR_CRAWLER_API_KEY'} = {}) {
  const base = site.siteUrl.replace(/\/$/, '');
  const url = (p) => `${base}${p}`;
  const selectors = `
        recordProps: {
          lvl0: {selectors: '', defaultValue: LVL0},
          lvl1: 'main h1',
          lvl2: 'main h2',
          lvl3: 'main h3',
          lvl4: 'main h4',
          lvl5: 'main h5',
          content: 'main p, main li, main td',
          pageRank: PAGE_RANK,
        },
        // One record per heading with its paragraphs (fewer records; the program caps at 10,000).
        aggregateContent: true,
        recordVersion: 'v3',`;
  const actions = CRAWL_SECTIONS.map(
    (s) => `    {
      indexName: ${quote(indexName)},
      pathsToMatch: [${s.paths.map((p) => quote(url(p))).join(', ')}],
      recordExtractor: ({helpers}) =>
        helpers.docsearch({${selectors.replace('LVL0', quote(s.lvl0)).replace('PAGE_RANK', quote(String(s.pageRank)))}
        }),
    },`,
  );
  return `// Algolia Crawler configuration for ${base} (generated by \`pnpm search-index ${site.folder ?? site.lang}\`).
// Paste into the Crawler editor (Algolia dashboard > Data sources > Crawler > your crawler > Editor).
// Records follow the DocSearch v3 schema adev's search service expects; lvl0 is "Docs",
// "Tutorials" or "Reference" because adev switches icons and package badges on those values.
new Crawler({
  appId: ${quote(appId)},
  apiKey: ${quote(apiKey)}, // the Crawler's own write key, never the search-only key from site.json
  indexPrefix: '',
  rateLimit: 8,
  maxDepth: 10,
  startUrls: [${quote(url('/'))}],
  sitemaps: [${quote(url('/sitemap.xml'))}], // written by \`pnpm build\` (post-process step)
  discoveryPatterns: [${quote(url('/**'))}],
  exclusionPatterns: [${CRAWL_EXCLUSIONS.map((p) => quote(url(p))).join(', ')}],
  ignoreCanonicalTo: false,
  // Pages are prerendered, so the HTML already holds the content; switch to true only if records come out empty.
  renderJavaScript: false,
  actions: [
${actions.join('\n')}
  ],
  initialIndexSettings: {
    ${quote(indexName)}: {
      attributesForFaceting: ['type', 'lang', 'language', 'version'],
      attributesToRetrieve: ['hierarchy', 'content', 'anchor', 'url', 'url_without_anchor', 'type'],
      attributesToHighlight: ['hierarchy', 'content'],
      attributesToSnippet: ['content:10'],
      camelCaseAttributes: ['hierarchy', 'content'],
      searchableAttributes: [
        'unordered(hierarchy.lvl0)',
        'unordered(hierarchy.lvl1)',
        'unordered(hierarchy.lvl2)',
        'unordered(hierarchy.lvl3)',
        'unordered(hierarchy.lvl4)',
        'unordered(hierarchy.lvl5)',
        'unordered(hierarchy.lvl6)',
        'content',
      ],
      distinct: true,
      attributeForDistinct: 'url',
      customRanking: ['desc(weight.pageRank)', 'desc(weight.level)', 'asc(weight.position)'],
      ranking: ['words', 'filters', 'typo', 'attribute', 'proximity', 'exact', 'custom'],
      highlightPreTag: '<span class="algolia-docsearch-suggestion--highlight">',
      highlightPostTag: '</span>',
      minWordSizefor1Typo: 3,
      minWordSizefor2Typos: 7,
      allowTyposOnNumericTokens: false,
      minProximity: 1,
      ignorePlurals: true,
      advancedSyntax: true,
      attributeCriteriaComputedByMinProximity: true,
      removeWordsIfNoResults: 'allOptional',
    },
  },
});
`;
}

/** Request to start a crawl (Crawler REST API, HTTP basic auth with the Crawler credentials). */
export function reindexRequest({crawlerId, userId, apiKey}) {
  if (!crawlerId) throw new Error('no crawler id: set search.crawlerId in site.json (the UUID in the Crawler dashboard URL)');
  if (!userId || !apiKey) throw new Error('set ALGOLIA_CRAWLER_USER_ID and ALGOLIA_CRAWLER_API_KEY (Crawler dashboard > Settings), not your search keys');
  return {
    url: `${CRAWLER_API}/crawlers/${encodeURIComponent(crawlerId)}/reindex`,
    init: {method: 'POST', headers: {Authorization: `Basic ${Buffer.from(`${userId}:${apiKey}`).toString('base64')}`}},
  };
}

/** Start a crawl; resolves with the task id. `fetchImpl` is injectable for tests. */
export async function triggerReindex(creds, fetchImpl = globalThis.fetch) {
  const {url, init} = reindexRequest(creds);
  const res = await fetchImpl(url, init);
  const body = await res.json().catch(() => ({}));
  if (!res.ok) throw new Error(`crawler reindex failed: HTTP ${res.status} ${body?.error?.message ?? ''}`.trim());
  return body.taskId ?? null;
}

/** Request a test query would send (search-only key, same host adev's client uses). */
export function queryRequest({appId, apiKey, indexName}, query = 'component') {
  return {
    url: `https://${appId}-dsn.algolia.net/1/indexes/${encodeURIComponent(indexName)}/query`,
    init: {
      method: 'POST',
      headers: {'X-Algolia-API-Key': apiKey, 'X-Algolia-Application-Id': appId, 'Content-Type': 'application/json'},
      body: JSON.stringify({query, hitsPerPage: 3, attributesToRetrieve: ['hierarchy', 'url', 'type']}),
    },
  };
}

/**
 * Run a test query against the configured index. Resolves with {nbHits, hits: [{url, lvl0, lvl1, type}]}.
 * Tells apart the three usual onboarding failures: wrong credentials, empty index, records of the
 * wrong shape (not DocSearch records).
 */
export async function verifySearch(search, query = 'component', fetchImpl = globalThis.fetch) {
  const {url, init} = queryRequest(search, query);
  const res = await fetchImpl(url, init);
  const body = await res.json().catch(() => ({}));
  if (!res.ok) throw new Error(`search query failed: HTTP ${res.status} ${body?.message ?? ''} (check appId, apiKey and indexName in site.json)`.trim());
  const hits = (body.hits ?? []).map((h) => ({url: h.url, lvl0: h.hierarchy?.lvl0 ?? null, lvl1: h.hierarchy?.lvl1 ?? null, type: h.type ?? null}));
  const problems = [];
  if (body.nbHits === 0) problems.push(`no hit for "${query}": the index is empty or the crawler did not run yet`);
  else if (!hits.every((h) => h.url && h.type && h.lvl0 !== null)) problems.push('records are not DocSearch records (hierarchy.lvl0, type, url missing): use the crawler configuration from `pnpm search-index <lang>`');
  return {nbHits: body.nbHits ?? 0, hits, problems};
}
