import assert from 'node:assert/strict';
import path from 'node:path';
import {after, before, describe, test} from 'node:test';
import {makeRepo, makeUpstream, read, removeDir, useRepo, write} from './helpers.mjs';

const repo = await makeRepo({example: true});
const upstream = await makeUpstream({git: false});
useRepo({root: repo.root, origin: upstream.dir});
const {renderFirebaseConfig, syncFirebaseConfig} = await import('../lib/firebase.mjs');

after(async () => {
  await removeDir(repo.root);
  await removeDir(upstream.dir);
});

const site = (lang, firebase) => JSON.stringify({lang, name: lang, englishName: lang, direction: 'ltr', domain: `${lang}.example`, repo: {owner: 'o', name: 'r'}, firebase});

describe('renderFirebaseConfig', () => {
  test('fails without languages', async () => {
    await assert.rejects(renderFirebaseConfig(), /no language configured/);
  });
  test('one hosting entry per language with upstream headers, targets grouped by project, staging optional', async () => {
    await write(path.join(repo.root, 'i18n/fr/site.json'), site('fr', {projectId: 'proj-fr', target: 'docs-fr'}));
    await write(path.join(repo.root, 'i18n/de/site.json'), site('de', {projectId: 'proj-shared', target: 'docs-de', site: 'de-site', stagingProjectId: 'proj-staging'}));
    const files = await renderFirebaseConfig();
    const fb = JSON.parse(files['firebase.json']);
    const rc = JSON.parse(files['.firebaserc']);
    assert.match(fb['//'], /Generated by/);
    assert.deepEqual(
      fb.hosting.map((h) => [h.target, h.public]),
      [
        ['docs-de', 'build/de/dist/bin/adev/dist/browser'],
        ['docs-de-staging', 'build/de/dist/bin/adev/dist/browser'],
        ['docs-fr', 'build/fr/dist/bin/adev/dist/browser'],
      ],
    );
    assert.ok(fb.hosting.every((h) => h.headers?.length && h.rewrites?.length), 'upstream header and rewrite rules are copied');
    assert.ok(!fb.hosting.some((h) => h.public === './build/browser'));
    assert.deepEqual(rc.projects, {default: 'proj-shared', staging: 'proj-staging'});
    assert.deepEqual(rc.targets['proj-shared'].hosting, {'docs-de': ['de-site']});
    assert.deepEqual(rc.targets['proj-fr'].hosting, {'docs-fr': ['proj-fr']});
    assert.deepEqual(rc.targets['proj-staging'].hosting, {'docs-de-staging': ['proj-staging']});
  });
  test('the example language is included only on request', async () => {
    const without = JSON.parse((await renderFirebaseConfig())['firebase.json']).hosting.map((h) => h.target);
    const withExample = JSON.parse((await renderFirebaseConfig({includeExample: true}))['firebase.json']).hosting.map((h) => h.target);
    assert.ok(!without.includes('docs-example'));
    assert.ok(withExample.includes('docs-example'));
  });
});

describe('syncFirebaseConfig', () => {
  before(() => write(path.join(repo.root, 'i18n/fr/site.json'), site('fr', {projectId: 'proj-fr', target: 'docs-fr'})));
  test('check mode reports stale files without writing; write mode writes and is then clean', async () => {
    const check = await syncFirebaseConfig({check: true});
    assert.deepEqual(check.stale.sort(), ['.firebaserc', 'firebase.json']);
    assert.deepEqual(check.written, []);
    const written = await syncFirebaseConfig();
    assert.deepEqual(written.written.sort(), ['.firebaserc', 'firebase.json']);
    assert.ok((await read(path.join(repo.root, 'firebase.json'))).endsWith('\n'));
    const again = await syncFirebaseConfig({check: true});
    assert.deepEqual(again.stale, []);
    await write(path.join(repo.root, '.firebaserc'), '{}');
    assert.deepEqual((await syncFirebaseConfig({check: true})).stale, ['.firebaserc']);
  });
});
